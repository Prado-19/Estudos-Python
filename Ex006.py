numeroDigitado = int(input('Digite um número '))
dobroDoNúmeroDigitado = numeroDigitado * 2
triploDoNumeroDigitado = numeroDigitado * 3
raizQuadradaDoNumeroDigitado = numeroDigitado ** (1/2)
print('O dobro é {}'.format(dobroDoNúmeroDigitado))
print('O triplo é {}'.format(triploDoNumeroDigitado))
print('A raiz quadrada é {:.2f}'.format(raizQuadradaDoNumeroDigitado))